/// The ASCII origin of `raw` (JS `new URL(raw).origin`).
pub fn url_origin(raw: &str) -> anyhow::Result<String> {
    let url = url::Url::parse(raw).with_context(|| format!("invalid URL {raw:?}"))?;
    Ok(url.origin().ascii_serialization())
}

/// `host[:port]` of an exact http(s) origin, or an error if `origin` is not one.
fn exact_origin_host(origin: &str) -> anyhow::Result<String> {
    let url = url::Url::parse(origin).with_context(|| format!("invalid origin {origin:?}"))?;
    if !matches!(url.scheme(), "http" | "https") {
        bail!("origin {origin:?} is not http(s)");
    }
    if url.origin().ascii_serialization() != origin {
        bail!("origin {origin:?} is not an exact origin");
    }
    let host = url.host_str().context("origin has no host")?;
    Ok(match url.port() {
        Some(port) => format!("{host}:{port}"),
        None => host.to_owned(),
    })
}

fn unix_secs_u32() -> u32 {
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(1);
    u32::try_from(secs).unwrap_or(u32::MAX)
}

