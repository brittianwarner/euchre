/// HTTP listener settings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HttpConfig {
    /// Address to bind. `[::]:PORT` from the environment, `127.0.0.1:0` in local mode.
    pub bind: SocketAddr,
    /// Whether cookies get `Secure` (true when the public origin is https).
    pub secure_cookies: bool,
    /// `EUCHRE_TRUST_FORWARDED_FOR=1`: take the client IP for the per-IP buckets (D11)
    /// and the engine Guard from the last `X-Forwarded-For` entry. Turn it on only when
    /// every request reaches the server through a proxy that appends that header (the
    /// Railway edge). Reached directly, a client writes the header itself and picks its
    /// own bucket. Off unless set, and always off in [`ServerConfig::local`].
    pub trust_forwarded_for: bool,
    /// `EUCHRE_TRUSTED_PROXIES`: when non-empty, the socket peer must be inside one of
    /// these networks before `X-Forwarded-For` counts. Empty trusts any peer once
    /// [`HttpConfig::trust_forwarded_for`] is on. Requires that flag.
    pub trusted_proxies: Vec<IpCidr>,
}

impl HttpConfig {
    /// Whether a request whose socket peer is `peer` may name its client in
    /// `X-Forwarded-For` ([`forwarded_for_trusted`] over this config).
    pub fn trusts_forwarded_for_from(&self, peer: Option<IpAddr>) -> bool {
        forwarded_for_trusted(self.trust_forwarded_for, &self.trusted_proxies, peer)
    }
}

/// Whether `X-Forwarded-For` names the client for a request from socket peer `peer`.
///
/// False when `enabled` is off. With `enabled` on, an empty `proxies` list trusts every
/// peer; otherwise the peer must be known and inside one of `proxies`. An IPv4-mapped
/// IPv6 peer (`::ffff:10.0.0.1`) matches IPv4 networks.
pub fn forwarded_for_trusted(enabled: bool, proxies: &[IpCidr], peer: Option<IpAddr>) -> bool {
    if !enabled {
        return false;
    }
    if proxies.is_empty() {
        return true;
    }
    peer.is_some_and(|peer| proxies.iter().any(|net| net.contains(peer)))
}

/// An IP network in CIDR form, for [`HttpConfig::trusted_proxies`].
///
/// Parses `10.0.0.0/8`, `fd00::/8`, or a bare address as a single host
/// (`/32`, `/128`). The address must have no host bits set beyond the prefix.
/// An IPv4-mapped IPv6 network with a prefix of 96 or more is stored as IPv4.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct IpCidr {
    network: IpAddr,
    prefix: u8,
}

impl IpCidr {
    /// A network of `prefix` leading bits. Fails when `prefix` is longer than the
    /// address family allows or `network` has host bits set.
    pub fn new(network: IpAddr, prefix: u8) -> anyhow::Result<Self> {
        let max = match network {
            IpAddr::V4(_) => 32,
            IpAddr::V6(_) => 128,
        };
        if prefix > max {
            bail!("prefix /{prefix} is longer than /{max} for {network}");
        }
        let (network, prefix) = match network {
            IpAddr::V6(v6) if prefix >= 96 => match v6.to_ipv4_mapped() {
                Some(v4) => (IpAddr::V4(v4), prefix - 96),
                None => (network, prefix),
            },
            other => (other, prefix),
        };
        let cidr = Self { network, prefix };
        if cidr.masked(network) != Some(network) {
            bail!("{network}/{prefix} has host bits set");
        }
        Ok(cidr)
    }

    /// A single address (`/32` or `/128`).
    pub fn host(addr: IpAddr) -> Self {
        let addr = addr.to_canonical();
        let prefix = match addr {
            IpAddr::V4(_) => 32,
            IpAddr::V6(_) => 128,
        };
        Self {
            network: addr,
            prefix,
        }
    }

    /// The network address.
    pub fn network(&self) -> IpAddr {
        self.network
    }

    /// The prefix length.
    pub fn prefix(&self) -> u8 {
        self.prefix
    }

    /// Whether `ip` is inside this network. An IPv4-mapped IPv6 address is compared
    /// as IPv4; an IPv4 address matches an IPv6 network through its mapped form.
    pub fn contains(&self, ip: IpAddr) -> bool {
        let ip = match (self.network, ip.to_canonical()) {
            (IpAddr::V6(_), IpAddr::V4(v4)) => IpAddr::V6(v4.to_ipv6_mapped()),
            (_, ip) => ip,
        };
        self.masked(ip) == Some(self.network)
    }

    /// Parse a comma-separated list: entries trimmed, empty entries dropped. The
    /// error names the first entry that is not an address or CIDR.
    pub fn parse_list(raw: &str) -> anyhow::Result<Vec<Self>> {
        raw.split(',')
            .map(js_trim)
            .filter(|entry| !entry.is_empty())
            .map(str::parse)
            .collect()
    }

    /// `ip` with the host bits cleared, or `None` when the families differ.
    fn masked(&self, ip: IpAddr) -> Option<IpAddr> {
        match (self.network, ip) {
            (IpAddr::V4(_), IpAddr::V4(v4)) => {
                let mask = u32::MAX
                    .checked_shl(32 - u32::from(self.prefix))
                    .unwrap_or(0);
                Some(IpAddr::V4(Ipv4Addr::from(u32::from(v4) & mask)))
            }
            (IpAddr::V6(_), IpAddr::V6(v6)) => {
                let mask = u128::MAX
                    .checked_shl(128 - u32::from(self.prefix))
                    .unwrap_or(0);
                Some(IpAddr::V6(Ipv6Addr::from(u128::from(v6) & mask)))
            }
            _ => None,
        }
    }
}

impl FromStr for IpCidr {
    type Err = anyhow::Error;

    fn from_str(s: &str) -> anyhow::Result<Self> {
        let invalid = || format!("{s:?} is not an IP address or CIDR (for example 10.0.0.0/8)");
        match s.split_once('/') {
            None => s.parse::<IpAddr>().map(Self::host).with_context(invalid),
            Some((addr, prefix)) => {
                let network = addr.parse::<IpAddr>().with_context(invalid)?;
                if prefix.is_empty()
                    || prefix.len() > 3
                    || !prefix.bytes().all(|b| b.is_ascii_digit())
                {
                    bail!(invalid());
                }
                let prefix = prefix.parse::<u8>().with_context(invalid)?;
                Self::new(network, prefix).with_context(invalid)
            }
        }
    }
}

impl fmt::Display for IpCidr {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}/{}", self.network, self.prefix)
    }
}

