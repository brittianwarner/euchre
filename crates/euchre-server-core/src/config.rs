//! Environment + secrets (05 §2.1, §5.1, §6, §13). Owned by lane SERVER-FOUNDATION.
//!
//! [`ServerConfig::from_env`] reads the same variables the TS server reads, with the
//! same names, defaults and dev fallbacks, and refuses to boot a deployment with a
//! missing, short, shared or well-known secret. [`ServerConfig::local`] builds the
//! embedded/desktop configuration: loopback HTTP, a spawned engine on a free loopback
//! port, strict Origin checks, and secrets (including the engine admin token)
//! generated once with the OS CSPRNG and kept in `data_dir/secrets.json` (0600).
//!
//! "Local dev" means `RIVET_ENDPOINT` is unset or empty, exactly as TS
//! `isLocalDev()`. A "deployment" is `NODE_ENV=production` or a remote engine.
//! Every config value is plain data; nothing here talks to the engine. The only
//! network touch is [`pick_local_engine_port`], which binds and releases loopback ports.
//!
//! `X-Forwarded-For` is never trusted by default, in any mode. Set
//! `EUCHRE_TRUST_FORWARDED_FOR=1` where every request arrives through a proxy that
//! appends it (the Railway edge), and optionally `EUCHRE_TRUSTED_PROXIES` (comma-separated
//! CIDRs) to require the socket peer to be that proxy. See [`HttpConfig`].

