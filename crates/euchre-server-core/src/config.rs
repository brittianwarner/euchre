    fn cfg(pairs: &[(&str, &str)]) -> anyhow::Result<ServerConfig> {
        let map: HashMap<String, String> = pairs
            .iter()
            .map(|(k, v)| ((*k).to_owned(), (*v).to_owned()))
            .collect();
        ServerConfig::from_map(&map)
    }

    fn prod(extra: &[(&str, &str)]) -> Vec<(&'static str, String)> {
        let mut base: Vec<(&'static str, String)> = vec![
            ("NODE_ENV", "production".into()),
            (
                "RIVET_ENDPOINT",
                "http://rivet-engine.railway.internal:6420".into(),
            ),
            ("RIVET_NAMESPACE", "euchre".into()),
            ("RIVET_TOKEN", "admin-token".into()),
            ("APP_URL", "https://euchre.example".into()),
            (
                "ALLOWED_ORIGINS",
                "https://euchre.example, https://www.euchre.example".into(),
            ),
            ("EUCHRE_ACTOR_JWT_SECRET", S1.into()),
            ("EUCHRE_INTERNAL_TOKEN", S2.into()),
            ("EUCHRE_IDENTITY_SECRET", S3.into()),
        ];
        for (k, v) in extra {
            base.retain(|(bk, _)| bk != k);
            base.push((leak(k), (*v).to_owned()));
        }
        base
    }

    fn leak(s: &str) -> &'static str {
        Box::leak(s.to_owned().into_boxed_str())
    }

    fn cfg_owned(pairs: &[(&'static str, String)]) -> anyhow::Result<ServerConfig> {
        let map: HashMap<String, String> = pairs
            .iter()
            .map(|(k, v)| ((*k).to_owned(), v.clone()))
            .collect();
        ServerConfig::from_map(&map)
    }

