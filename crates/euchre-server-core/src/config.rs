/// A secret string whose `Debug` output never shows the value.
#[derive(Clone, PartialEq, Eq)]
pub struct Secret(String);

impl Secret {
    /// Wrap a secret value.
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    /// The secret value. Call only where the bytes are actually needed (signing, comparing).
    pub fn expose(&self) -> &str {
        &self.0
    }

    /// The secret as bytes (UTF-8), as TS `TextEncoder` produces for HMAC keys.
    pub fn as_bytes(&self) -> &[u8] {
        self.0.as_bytes()
    }

    /// Length in UTF-16 code units, as JS `.length` counts it.
    pub fn js_len(&self) -> usize {
        js_len(&self.0)
    }
}

impl fmt::Debug for Secret {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("Secret(<redacted>)")
    }
}

/// Where a resolved secret came from. Safe to log.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SecretSource {
    /// Read from the named environment variable.
    Env(&'static str),
    /// The well-known dev fallback (local dev only).
    DevFallback,
    /// Generated by [`ServerConfig::local`] and persisted in `secrets.json`.
    Generated,
    /// Generated for this process only (persisting failed); lost on restart.
    Ephemeral,
}

/// A secret plus its provenance.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedSecret {
    /// The value.
    pub value: Secret,
    /// Where it came from.
    pub source: SecretSource,
}

